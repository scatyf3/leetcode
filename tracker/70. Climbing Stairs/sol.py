class Solution:
    def climbStairs(self, n: int) -> int:
        # n step
        # 1+2 step
        # dp[i] = dp[i-1] + dp[i-2]
        dp = [0 for i in range(n)]
        if n==0:
            return 0
        if n==1:
            return 1
        if n==2:
            return 2
        dp[0]=1
        dp[1]=2 
        for i in range(n):
            if i==0 or i==1:
                continue
            else:
                dp[i] = dp[i-1] + dp[i-2]
        return dp[n-1]


# ============================================================
# edge case / init 的几种更好写法
# ============================================================
#
# 特例是从哪冒出来的:递推式 dp[i] = dp[i-1] + dp[i-2] 在 i < 2 时下标要越界(变负数),
# 所以 i=0,1 必须由 base case 直接给出。真正要处理的边界只有这一个,
# 上面那三个 if 是被"数组预分配 + 下标错位"额外制造出来的。
#
#
# ---- 写法 A:下标对齐,多开一格 ----------------------------
# 关键是让 dp 的下标 == 阶数(你原来是 dp[i] 表示第 i+1 阶,差了 1,
# 所以初值要写成 dp[1]=2 这种"算过一次"的值,还得手动 -1 才能返回)。
#
#     dp = [0] * (n + 1)        # 多开一格才放得下 dp[n]
#     dp[0] = 1                 # 站着不动算一种(空爬法)
#     dp[1] = 1                 # 只有 "1"
#     for i in range(2, n + 1):
#         dp[i] = dp[i-1] + dp[i-2]
#     return dp[n]
#
# dp[0]=1 是这里唯一需要想一下的:它让 dp[2] = dp[1] + dp[0] = 2 自动成立,
# 于是 "第 2 阶有 2 种" 这个事实不用再手写一遍。和 206 的 dummy head 是同一招:
# 造一个语义上成立的"空状态",让通用逻辑覆盖掉原本的特例。
# n=1 时 range(2,2) 是空的,循环空转直接返回 dp[1],不需要 if。
# (n=0 仍会在 dp[1]=1 越界,但本题约束 1 <= n <= 45,不用管)
#
#
# ---- 写法 B:数组长出来,而不是预分配 ---------------------
# 越界的根源是"先按 n 开好长度、再往里填"。改成 append,长度永远等于已填的个数:
#
#     dp = [1, 1]               # dp[0], dp[1] —— 初值即数组本体
#     for i in range(2, n + 1):
#         dp.append(dp[i-1] + dp[i-2])
#     return dp[n]
#
# n=0 和 n=1 都不进循环,直接命中初值。一个 if 都不用,也不可能越界。
#
#
# ---- 写法 C:滚动变量,O(1) 空间 ---------------------------
# dp[i] 只依赖前两项,整个数组是浪费的。没有数组,就没有下标,也就没有越界:
#
#     a, b = 1, 1               # a = dp[i-2], b = dp[i-1]
#     for _ in range(n - 1):    # 从 dp[1] 推到 dp[n],共 n-1 步
#         a, b = b, a + b
#     return b
#
# 和 206 里 head.next, prev, head = prev, head, head.next 是同一个手法:
# 右边整个先求值,所以不需要 tmp。这里的 "init" 就是边界本身,
# 循环转几次由 range 决定 —— 边界条件被塞进了循环次数里,而不是 if 里。
#
#
# ---- 写法 D:记忆化递归,base case 就是 init --------------
#     from functools import cache
#
#     @cache
#     def f(i):
#         if i <= 1:            # 一句话覆盖 i=0 和 i=1
#             return 1
#         return f(i-1) + f(i-2)
#     return f(n)
#
# 自顶向下时 base case 天然就是初值,不存在"先开数组再填"这一步。
# 代价是递归栈 O(n),n=45 没问题,但这类题一般还是写迭代。
#
#
# ---- 三条通用规律 ----------------------------------------
# 1. 让 base 有意义,而不是特判它。dp[0]=1("什么都不做也是一种方案")
#    比 if n==1: return 1 更好,因为前者参与递推、能被后面的项用上。
# 2. 能用循环边界表达的条件,别写进循环体当 if。
#    range(2, n+1) 完胜 for i in range(n) + if i==0 or i==1: continue。
# 3. 同一个事实别写两遍。原来的 return 2 和 dp[1]=2 是同一个常量,
#    将来改递推口径(比如 746 带权版)容易只改一处、漏掉另一处。
