# 滑动窗口, 形状 1(外层枚举左端点 l, 内层向右扩 r)。对照版本见 sol2.py(形状 2)。
# 两版算法完全相同 —— l/r 都单调走一遍, 摊还 O(n), 实测操作次数几乎一样
# (35735 字符/5 字母表: sol2 max() 调用 64647 次, 本版 65247 次)。
# 区别只在"while 停在哪一侧", 以及由此产生的特判数量: sol2 零特判, 本版三个。
#
# 不变式: 内层退出时, 窗口 [l, r) 是【第一个非法】的窗口(或 r 已撞边界)。
#         所以结算的是它退一格, 即 [l, r-1), 长度 r-l-1。
#
# r 的语义和 sol2 不同 —— 这是所有 ±1 的来源:
#   sol2 : r 指【元素】(刚纳入的字符下标), cnt 覆盖闭区间 [l, r], 长度 r-l+1
#   本版 : r 指【缝】  (下一个待纳入的位置), cnt 覆盖半开   [l, r), 长度 r-l
#          又因为停在第一个非法处, 再退一格 -> r-l-1
#   注意: 结算对象 [l, r-1) 和 cnt 覆盖的 [l, r) 不是同一段, sol2 里这两者永远相同。
#
# 三个特判都是"后置条件里有『或』"的代价 —— 内层有两条退出路径
# (预算耗尽 / 撞右边界), 一个 r-l-1 要同时为两者负责:
#   1. max(..., default=0)  空窗口时 cnt 为空, max() 会抛 ValueError
#   2. if r < n             撞边界时【只推 r 不纳入】。这个空推是把两条退出路径
#                           的下标对齐的补丁: 空推后 r = n+1, 于是 r-l-1 = n-l,
#                           正好是 [l, n) 全合法时的长度。缺了它这一支就差 1。
#   3. l < n                否则 s="" 时 s[l] 直接 IndexError。
#                           sol2 靠初始状态天然正确, 一个守卫都不用。
#
# 形状 1 买到了什么: 把 res_max 换成 out.append(r-l-1)(外层条件同时改成 while l < n)
# 就能返回"以每个 i 开头的最长合法窗口"这个按【左端点】索引的数组。
# 但这【不是】sol2 做不到的事 —— sol2 在收缩处挂一行 ans[l] = r - l、循环后补上尾巴,
# 同样能吐出它(对拍 5000 组零错)。两个形状走的是同一条单调阶梯:
#     f(l) = 使 [l,r] 合法的最大 r    <->    g(r) = 使 [l,r] 合法的最小 l
# 两者都单调不减且互为逆函数, 知道一个等于知道另一个。走完阶梯的代价 O(n) 相同,
# 拿到的【信息量】也相同 => 能力相同。差的只是哪个方向的数组【顺手】:
#   sol2 按 r 索引免费(结算那行就是), 按 l 索引多两笔; 本版反之。
# 人体工学差异, 不是能力差异。
# => 形状 1 真正不可替代的只剩"state 删不掉"和"删除很贵"两类, "答案是数组"不算。
#    本版净亏(买到一点人体工学, 付了三个特判), 答案卡/默认写法认 sol2。
#
# 对拍: 与 sol2 在 n<=9 的 AB 全枚举 + 20000 组随机串上零分歧。
from collections import Counter


class Solution:
    def characterReplacement(self, s: str, k: int) -> int:
        n = len(s)
        cnt = Counter()
        l = r = 0
        res_max = 0
        while r <= n and l < n:
            cur_max = max(cnt.values(), default=0)
            while k - (r - l - cur_max) >= 0 and r <= n:   # 还有替换预算就继续扩
                if r < n:
                    cnt[s[r]] += 1                          # 撞边界时只推 r, 不纳入
                r += 1
                cur_max = max(cnt.values(), default=0)
            res_max = max(r - l - 1, res_max)               # 退一格才是最后一个合法窗口
            cnt[s[l]] -= 1                                  # 收缩 l: 无条件, 换下一个左端点
            l += 1
        return res_max
