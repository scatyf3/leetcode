class Solution:
    def threeSum(self, nums: list[int]) -> list[list[int]]:
        '''
        Input:
        - nums: List[int], 3 <= n <= 3000, -1e5 <= nums[i] <= 1e5
        Target: 所有和为 0 且下标互不相同的三元组, 结果不含重复三元组
        Return: List[List[int]]
        Output: list of triplets

        解法: 固定 i + 内层哈希查补数   O(n^2) 时间 / O(n) 空间
        【答案正确, 但重复元素多的输入会 TLE —— 修法见 sol3.py】

        这是 sol1.py 那个错解的最小正确形态。相对 sol1 只改了一件事:
            哈希表建在**内层**, 每固定一个 i 就重置; 而不是一开始把 n^2/2 个 pair 全预存。
        由此 sol1 的两个 bug 一起消失:
            - 空间从 O(n^2) 降到 O(n)
            - seen 里只有"下标在 (i, j) 之间"的值 => 不可能拿 i 或 j 自己去凑第三个数
        '''
        res = set()
        n = len(nums)
        for i in range(n):
            seen = set()                          # 只装本轮 i 已经走过的 nums[j]
            for j in range(i + 1, n):
                c = -(nums[i] + nums[j])          # 需要的第三个数
                if c in seen:                     # ← 必须先查
                    res.add(tuple(sorted((nums[i], nums[j], c))))   # 规范化后进 set 去重
                seen.add(nums[j])                 # ← 再把自己加进去
        return [list(t) for t in res]

        '''
        先查后加, 顺序不能反(这是正确性, 不是风格):
          nums = [-2, 1, 5], 正确答案是 []
          先查后加 -> []                 ✓
          先加后查 -> [(-2, 1, 1)]       ✗  那个 1 被当成配对的一半又当成第三个数
          原因: 先 add 会把 nums[j] 自己放进 seen, 于是 c == nums[j] 时自己匹配自己。

        Dry Run: nums = [-1, 0, 1, 2, -1, -4]
        i=0 (-1): j=1(0) c=1 不在 seen{} -> seen={0}
                  j=2(1) c=0 **在** seen -> 收 (-1,0,1)
                  j=3(2) c=-1 不在 seen{0,1}
                  j=4(-1) c=2 不在 seen{0,1,2}
                  j=5(-4) c=5 不在
        i=1 (0):  ... j=3(2) c=-2 无; j=4(-1) c=1 **在** seen{1,2} -> 收 (-1,0,1) 重复, set 挡掉
        i=3 (2):  j=4(-1) c=-1 不在 seen{}; j=5(-4) c=2 不在 seen{-1}
        i=4 (-1): j=5(-4) c=5 不在
        -> {(-1,0,1), (-1,-1,2)}

        为什么会 TLE (实测 n=3000, 本地):
        | 输入                | 本版(不排序) | sol3(排序去重) | 双指针 |
        |---------------------|-------------|---------------|--------|
        | 全 0 (最坏)          | 1.42s       | 0.00s         | 0.00s  |
        | 只有 -1/0/1 三种值    | 1.37s       | 0.00s         | 0.00s  |
        | 随机大范围(几乎全不同) | 0.66s       | 0.49s         | 0.43s  |

        根因不是 O(n^2) 本身, 是**同一个解被反复产出**:
          [0]*3000 时每一对 (i,j) 都命中, 要做 4.5e6 次 tuple(sorted(...)) + set.add,
          而它们全都在生成同一个 [0,0,0]。
        修法: 先排序, 然后 `if i and nums[i]==nums[i-1]: continue` 跳过重复的第一个数,
              3000 个 i 塌成 1 个。见 sol3.py。

        Test Cases (答案都对, 只是慢):
        [-1,0,1,2,-1,-4] -> [[-1,0,1],[-1,-1,2]]
        [-2,1,5]         -> []            先加后查的话会给出假解 [-2,1,1]
        [0,0,0,0]        -> [[0,0,0]]     sol1 在这里给 24 个
        [-1,2,0]         -> []            sol1 在这里给假解
        [0]*3000         -> [[0,0,0]]     正确但 1.4s, LeetCode 上 TLE
        '''
