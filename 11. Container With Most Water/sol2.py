class Solution:
    def maxArea(self, height: List[int]) -> int:
        '''
        Input:
        - height: List[int], 2 <= n <= 1e5, 0 <= height[i] <= 1e4
        Target: 选两根柱子当左右墙, 使 min(左墙, 右墙) * 两墙间距 最大
        Return: 该最大面积
        Output: int

        解法: 相向双指针 O(n) 时间 / O(1) 空间
        sol1.py 的 O(n^2) 在 n = 1e5 时 TLE(1e10 次运算), 这里把它降到 n 步。

        核心不变式: 最优的那一对, 始终在 [l, r] 区间内。
        每步只做一件事: 把当前的短板永久扔掉。
        扔它是安全的, 因为它的上限**已经算过了**:
          设 h[l] < h[r], 考察所有以 l 为左墙的其它配对 (l, j), j < r:
            高度: l 是短板 -> min 恒等于 h[l], 换谁当搭档都封顶, 涨不上去
            宽度: r 已是最远, 换谁都更窄
          两个维度都不可能更好 => 面积(l, j) <= 面积(l, r), 而后者刚刚结算完。
        反过来高的那根不能扔: 它现在只是被短板拖累, 换个高搭档还可能翻身。

        对比 LC42 接雨水: 那题要 L/R 前缀最大值数组, 因为位置 i 的水位由"远处两侧的最高柱"
        决定, 手上没有那个信息; 这题两面墙就在 l 和 r 上, 不需要任何预处理数组。
        判据: 这一格的答案依赖不依赖我手上没有的信息?
        '''
        l, r = 0, len(height) - 1
        best = 0
        while l < r:
            # 先结算当前这对, 再决定扔谁 —— 顺序不能反, 反了会漏掉这一对
            best = max(best, min(height[l], height[r]) * (r - l))
            if height[l] < height[r]:
                l += 1          # 左边是短板, 上限已结算, 扔掉
            else:
                r -= 1          # 右边是短板(或两边等高), 同理
        return best

        '''
        Dry Run: height = [2, 9, 9, 5]
          l=0 r=3  min(2,5)*3 = 6    best=6    h[0]=2 < h[3]=5 -> 扔 0, l 右移
          l=1 r=3  min(9,5)*2 = 10   best=10   h[1]=9 > h[3]=5 -> 扔 3, r 左移
          l=1 r=2  min(9,9)*1 = 9    best=10   等高 -> 走 else 扔 r
          l=1 r=1  退出
          return 10
        对照暴力枚举全部 6 对: (0,1)=2 (0,2)=4 (0,3)=6 (1,2)=9 (1,3)=10 (2,3)=5 -> 最大 10 ✓
        3 步 vs 6 对; n 大时是 n vs n^2/2。

        两个细节:
        1. 等高时 (h[l] == h[r]) 挪哪边都对: 此时两边都是短板, 各自的上限都已结算,
           扔任意一根都不会丢最优解。上面走 else 扔 r, 换成扔 l 结果一样。
        2. 循环条件是 l < r 不是 l <= r: l == r 时宽度为 0, 算它没错但没意义。

        Test Cases:
        [1,8,6,2,5,4,8,3,7] -> 49    经典样例, 答案是 (1,8) 这对
        [1,1]               -> 1     最小规模 n=2
        [2,9,9,5]           -> 10    上面的 dry run
        [1,2,4,3]           -> 4     答案 (1,3): min(2,3)*2, 不是最高的那两根
        [0,0]               -> 0     全 0
        [1,2,1]             -> 2     宽的那对 (0,2) 反而更优
        '''
